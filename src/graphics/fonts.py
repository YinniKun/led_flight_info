def text_width(text: str, font: Dict[str, list[str]] = FONT_3x5, tracking: int = 1) -> int:
    """Calculate pixel width of a string rendered with the given bitmap font."""
    width = 0
    chars = list(text.upper())
    for i, ch in enumerate(chars):
        glyph = font.get(ch, font.get(" "))
        glyph_width = len(glyph[0]) if glyph else 3
        width += glyph_width
        if i < len(chars) - 1:
            width += tracking
    return width


def draw_text(
    canvas_or_img: Union[Image.Image, Any],
    text: str,
    x: int,
    y: int,
    font: Dict[str, list[str]] = FONT_3x5,
    color: Tuple[int, int, int] = (255, 255, 255),
    tracking: int = 1,
) -> int:
    """
    Draw bitmap text directly onto PIL Image or MatrixCanvas.
    Returns the ending x coordinate.
    """
    img = canvas_or_img.image if hasattr(canvas_or_img, "image") else canvas_or_img
    cur_x = x

    for ch in text.upper():
        glyph = font.get(ch, font.get(" "))
        if not glyph:
            cur_x += 3 + tracking
            continue

        glyph_w = len(glyph[0])
        glyph_h = len(glyph)

        for row_idx, row in enumerate(glyph):
            py = y + row_idx
            if py < 0 or py >= img.height:
                continue
            for col_idx, bit in enumerate(row):
                px = cur_x + col_idx
                if px < 0 or px >= img.width:
                    continue
                if bit == "1":
                    img.putpixel((px, py), color)

        cur_x += glyph_w + tracking

    return cur_x
